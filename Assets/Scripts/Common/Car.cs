using Unity.VisualScripting;
using UnityEngine;
using System.Collections.Generic;
using UnityEngine.ProBuilder.MeshOperations;
using Unity.Cinemachine;

[RequireComponent(typeof(AudioSource))]
public class Car : MonoBehaviour
{
    public bool IsDead { get; protected set; }
    [Header("Car Properties")]
    public bool Grounded;
    [Tooltip("The potential damage generated by the current velocity of the car")]
    public float Damage;
    [Tooltip("The speed at which the car must travel (See Movement.cs for Player implementation.)")]
    public float Speed;
    [Tooltip("The speed at which the car must turn.")]
    public float TurnSpeed;
    public Boost CurrentBoost;
    [Header("Car Components")]
    public Health health;
    public Movement movement;
    public CarSounds carSounds;
    public Rigidbody physics;

    [Header("Extras")]
    [SerializeField] ImpactDetection frontImpactDetection;

    
    protected Vector3 currentVelocity; // Really meant for use with the BotCar
    int CurrentLap = 1;
    float DistanceFromNextWaypoint;
    AudioSource sound;
    float originalPitch;
    float originalVolume;
    List<Waypoint> completedWaypoints = new List<Waypoint>();
    protected Waypoint nextWaypoint;
    bool spawnEffectOnLand = false;    

    protected virtual void Awake()
    {
        health = GetComponent<Health>();
        movement = GetComponentInParent<Movement>();
        sound = GetComponent<AudioSource>();
        sound.volume = sound.volume / 4;
        physics = GetComponent<Rigidbody>();
        originalPitch = sound.pitch;
        originalVolume = sound.volume;
    }

    protected virtual void FixedUpdate()
    {

        RaycastHit info;

        IsDead = health.value <= 0;
        DistanceFromNextWaypoint = nextWaypoint ? Vector3.Distance(this.transform.position, nextWaypoint.transform.position) : 0.00f;

        if (!Grounded)
        {
            //
        }
        else
        {
            if (transform.localRotation.eulerAngles.z > 137f && transform.localRotation.eulerAngles.z < 260f)
            {
                Death();
            }
        }

        if (CurrentBoost && !CurrentBoost.isActiveAndEnabled)
        {
            CurrentBoost = null;
        }

        if (movement.currentLinearVelocity.magnitude > .1f)
        {
            float newPitch = Mathf.Clamp((((this is PlayerCar) ? movement.currentLinearVelocity.magnitude - movement.currentAngularVelocity.magnitude : currentVelocity.magnitude)) * .025f, .75f, Mathf.Infinity);
            sound.pitch = newPitch;
            sound.volume = newPitch * .175f;
            PlayInterruptingLoopSound(carSounds.AccelerateLoop);
        }
        else
        {
            sound.pitch = originalPitch;
            sound.volume = originalVolume / 2;
            PlayInterruptingLoopSound(carSounds.Idle);
        }
    }

    protected void LateUpdate()
    {
        physics.linearVelocity -= ((transform.up) * Time.deltaTime * 7) + (physics.centerOfMass * (physics.mass / 16));
    }

    protected virtual void OnCollisionEnter(Collision collision)
    {
        Rigidbody rb = collision.gameObject.GetComponent<Rigidbody>();
        Car otherCar = collision.gameObject.GetComponent<Car>();
        Health otherHealth = collision.gameObject.GetComponent<Health>();

        if (otherCar && Damage > otherCar.Damage && otherCar != this)
        {
            // This is the collision with another car
            if (GameSystem.instance.racePreferences.DealDamage)
            {
                otherCar.health.Damage((Damage - otherCar.Damage) * 2.5f);
            }
            
            GameFX.instance.SpawnImpactEffect(collision.GetContact(0).point);
        }
        else if (!otherCar && otherHealth)
        {
            // This is the collision with a prop or some other GameObject with a health script
            if (GameSystem.instance.racePreferences.DealDamage)
            {
                otherHealth.Damage(Damage);
            }
            
            GameFX.instance.SpawnImpactEffect(collision.GetContact(0).point);
        }

        if (collision.gameObject.CompareTag("Prop"))
        {
            if (rb)
            {
                rb.AddRelativeForce(transform.up * Damage * 3, ForceMode.Impulse); // Knocks around GameObjects with physics on them
                GameFX.instance.SpawnImpactEffect(collision.GetContact(0).point);
            }
            else
            {
                if (GameSystem.instance.racePreferences.DealDamage)
                {
                    health.Damage(Damage / 4);
                }
                
                GameFX.instance.SpawnImpactEffect(collision.GetContact(0).point);
            }
        }
    }

    private void OnCollisionStay(Collision collision)
    {
        if (collision.gameObject.layer == 7 || collision.gameObject.layer == 0) // Map Layer
        {
            if (Grounded == false)
            {
                Grounded = true;
                if (spawnEffectOnLand)
                {
                    GameFX.instance.SpawnLandingEffect(transform.position);
                }
            }
            else
            {

            }
        }
    }

    private void OnCollisionExit(Collision collision)
    {
        if (collision.gameObject.layer == 7 || collision.gameObject.layer == 0) // Map Layer
        {
            Grounded = false;
            if (Physics.Raycast(transform.localPosition, -transform.up, Mathf.Infinity, 7 | 0) && !Grounded)
            {
                spawnEffectOnLand = true;
                OnLanding();
            }
            else
            {
                spawnEffectOnLand = false;
            }
        }
    }

    protected virtual void OnLanding()
    {

    }

    private void OnTriggerEnter(Collider other)
    {
        if (other.tag.Contains("Boost") && this is PlayerCar)
        {
            Boost boost = other.gameObject.GetComponent<Boost>();

            GiveBoost(boost);
        }
    }

    public void GiveBoost(Boost boost)
    {
        if (boost is HealthBoost)
        {
            health.Give(boost.value);
            this.CurrentBoost.Activate();
        }
        else
        {
            this.CurrentBoost = boost;
            this.CurrentBoost.Activate();
        }
    }

    public Rigidbody GetPhysics()
    {
        if (physics)
        {
            return physics;
        }
        else
        {
            return null;
        }
    }

    public void NextLap()
    {
        CurrentLap++;
    }

    public int GetCurrentLap()
    {
        return CurrentLap;
    }

    public float GetDistanceFromNextWaypoint()
    {
        return DistanceFromNextWaypoint;
    }

    public int GetCompletedWaypoints()
    {
        return completedWaypoints.Count;
    }

    protected virtual void OnDeath()
    {

    }

    protected virtual void Death()
    {
        IsDead = true;
        GameFX.instance.SpawnExplosion(transform.position);
        GameFX.instance.SpawnSmokeStreamEffect(transform.position);
        OnDeath();
    }


    // Sounds


    protected void PlaySound(AudioClip clip)
    {
        sound.PlayOneShot(clip);
    }

    protected void PlayInterruptingSound(AudioClip clip)
    {
        if (sound.isPlaying && sound.clip != clip)
        {
            sound.Stop();
        }
        if (!sound.isPlaying)
        {
            PlaySound(clip);
        }
    }

    protected void PlayLoopingSound(AudioClip clip)
    {
        sound.clip = clip;
        if (!sound.loop)
        {
            sound.loop = true;
        }

        sound.Play();
    }

    protected void PlayInterruptingLoopSound(AudioClip clip)
    {
        if (sound.isPlaying && sound.clip != clip)
        {
            sound.Stop();
        }
        if (!sound.isPlaying)
        {
            PlayLoopingSound(clip);
        }
    }

    void Damaged()
    {

    }

    // Message Events

    void AddCompletedWaypoints(Waypoint waypoint)
    {
        if (completedWaypoints.Contains(waypoint))
        {
            return;
        } 
        completedWaypoints.Add(waypoint);
    }

    void ClearCompletedWaypoints()
    {
        completedWaypoints.Clear();
    }

    virtual protected void SetNextWaypoint(Waypoint waypoint)
    {
        nextWaypoint = waypoint;
    }

    public Waypoint GetNextWaypoint()
    {
        return nextWaypoint;
    }
}
